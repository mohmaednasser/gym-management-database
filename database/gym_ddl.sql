CREATE TABLE MEMBERSHIP_TYPE
(
	Membership_Type_ID INT IDENTITY(1,1) ,
	Name VARCHAR(50) NOT NULL ,
	Duration VARCHAR(50) NOT NULL ,
	Price INT NOT NULL ,
	CONSTRAINT MT1 PRIMARY KEY(Membership_Type_ID) ,
	CONSTRAINT MT2 CHECK(Name IN ('Monthly','3-Month','6-Month','Yearly')) ,
	CONSTRAINT MT3 CHECK(Price > 0)
) ;
GO

CREATE TABLE DISCOUNTS
(
	Discount_ID INT IDENTITY(1,1) ,
	Name VARCHAR(50) NOT NULL ,
	Value DEC(5,2) NOT NULL ,
	Type VARCHAR(50) NOT NULL ,
	Start_Date DATE DEFAULT GETDATE() ,
	End_Date DATE NOT NULL ,
	CONSTRAINT D1 PRIMARY KEY(Discount_ID) ,
	CONSTRAINT D2 CHECK(Value > 0) ,
	CONSTRAINT D3 CHECK(Start_Date >= GETDATE()) ,
	CONSTRAINT D4 CHECK(End_Date >= Start_Date)
) ;
GO

CREATE TABLE MEMBERSHIP
(
	Membership_ID INT IDENTITY(1,1) ,
	Start_Date DATE DEFAULT GETDATE() ,
	End_Date DATE NOT NULL ,
	Price INT NOT NULL ,
	Status VARCHAR(50) NOT NULL ,
	#_Allowed_Sessions INT NOT NULL ,
	Discount_ID INT ,
	CONSTRAINT M1 PRIMARY KEY(Membership_ID) ,
	CONSTRAINT M2 CHECK(Start_Date = GETDATE()) ,
	CONSTRAINT M3 CHECK(Price > 0) ,
	CONSTRAINT M4 CHECK(#_Allowed_Sessions > 0) ,
	CONSTRAINT M5 CHECK(Status IN ('Active','Expired','Cancelled')),
	CONSTRAINT M6 FOREIGN KEY(Discount_ID) REFERENCES DISCOUNTS(Discount_ID)
		ON UPDATE CASCADE 
) ;
GO

CREATE TABLE MEMBERSHIP_PACKAGES
